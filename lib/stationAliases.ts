/**
 * 入力された駅名を正式名称に揃える。
 *   "　京都　河原町駅 " → "京都河原町"
 *   "三条(京都府)"      → "三条"
 *   "宝ヶ池"            → "宝ケ池"
 * 何も当たらなければ整えた文字列をそのまま返す（Transit API に回る）。
 */
export function normalizeStationName(raw: string): string {
  let s = raw.normalize("NFKC");            // 全角英数・全角スペース → 半角
  s = s.replace(/\s+/g, "");                // 空白を全部消す
  s = s.replace(/[（(][^）)]*[）)]$/, "");   // 末尾の「(京都府)」のような補足を消す
  s = s.replace(/駅$/, "");                 // 末尾の「駅」
  return STATION_ALIASES[s] ?? s;
}